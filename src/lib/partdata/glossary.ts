/**
 * Canonical name to send to partdata's BOM matcher, so "ST" or "TI" in a spreadsheet can be
 * compared with "意法半导体" / "德州仪器" stored in ezPLM. Unknown names pass through unchanged.
 */
export function manufacturerCanonical(name: string | null | undefined) {
  const v = String(name || "").trim();
  if (!v) return "";
  const abbr = ABBREVIATIONS[v.toUpperCase().replace(/[.,]/g, "").replace(/\s+(INC|CORP|LTD|CO)$/, "")];
  if (abbr) return abbr;
  return MANUFACTURER_RULES.find((r) => r.re.test(v))?.name ?? v;
}

/** English display name for a manufacturer; unchanged when it is already Latin or unknown. */
export function manufacturerEn(name: string | null | undefined) {
  const v = String(name || "").trim();
  if (!hasCjk(v)) return v;
  const hit = MANUFACTURER_RULES.find((r) => r.re.test(v));
  if (hit) return hit.name;
  // "罗姆半导体（上海）有限公司 (ROHM)"-style values: keep the Latin part.
  const latin = v.match(/[A-Za-z][A-Za-z0-9 .,&+-]{1,}/g)?.find((s) => /[A-Za-z]{2}/.test(s));
  return latin ? latin.trim() : v;
}

/** English category label; the original is kept when there is no translation. */
export function categoryEn(name: string | null | undefined): string {
  const v = String(name || "").trim();
  if (!v) return "";
  if (CATEGORY_EN[v]) return CATEGORY_EN[v];
  // ezPLM paths sometimes arrive as "整流器 > 二极管阵列"
  if (v.includes(">")) return v.split(">").map((s) => categoryEn(s.trim())).join(" › ");
  return v;
}

/** Lifecycle codes from ezPLM. */
export function lifecycleEn(v: string | null | undefined) {
  const s = String(v || "").trim();
  const map: Record<string, string> = {
    量产: "Active",
    在产: "Active",
    停产: "Obsolete",
    不推荐: "Not recommended",
    即将停产: "Last time buy",
    预发布: "Preview",
    active: "Active",
  };
  return map[s] ?? map[s.toLowerCase()] ?? s;
}
