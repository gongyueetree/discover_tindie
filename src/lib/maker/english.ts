const entries = Object.entries(terms).sort((a, b) => b[0].length - a[0].length);
export function terminology(text: string) {
  let s = text;
  for (const [a, b] of entries) s = s.split(a).join(` ${b} `);
  return s
    .replace(/[，、]/g, ", ")
    .replace(/；/g, "; ")
    .replace(/：/g, ": ")
    .replace(/（/g, " (")
    .replace(/）/g, ")")
    .replace(/。/g, ".")
    .replace(/\s+/g, " ")
    .trim();
}
export function withUnit(value: unknown, unit?: string) {
  const v = String(value ?? "").trim(),
    u = (unit || "").trim();
  if (!u) return v;
  return v.toLowerCase().endsWith(u.toLowerCase()) ? v : `${v} ${u}`;
}
